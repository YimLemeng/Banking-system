
CREATE TABLE users
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE,
    phone_number VARCHAR(20)                             NOT NULL,
    username     VARCHAR(50),
    email        VARCHAR(255),
    password     VARCHAR(255)                            NOT NULL,
    role         VARCHAR(255)                            NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (id)
);

ALTER TABLE users
    ADD CONSTRAINT uc_users_email UNIQUE (email);

ALTER TABLE users
    ADD CONSTRAINT uc_users_phone_number UNIQUE (phone_number);

ALTER TABLE users
    ADD CONSTRAINT uc_users_username UNIQUE (username);


CREATE TABLE customers
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at           TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at           TIMESTAMP WITH TIME ZONE,
    first_name           VARCHAR(255)                            NOT NULL,
    last_name            VARCHAR(255)                            NOT NULL,
    email                VARCHAR(255)                            NOT NULL,
    phone_number         VARCHAR(255),
    national_or_passport VARCHAR(255)                            NOT NULL,
    address              VARCHAR(255),
    user_id              BIGINT,
    CONSTRAINT pk_customers PRIMARY KEY (id)
);

ALTER TABLE customers
    ADD CONSTRAINT uc_customers_email UNIQUE (email);

ALTER TABLE customers
    ADD CONSTRAINT FK_CUSTOMERS_ON_USER FOREIGN KEY (user_id) REFERENCES users (id);


CREATE TABLE accounts
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE,
    account_number VARCHAR(255)                            NOT NULL,
    account_type   VARCHAR(255)                            NOT NULL,
    balance        DECIMAL(19, 4)                          NOT NULL,
    status         VARCHAR(255)                            NOT NULL,
    customer_id    BIGINT                                  NOT NULL,
    CONSTRAINT pk_accounts PRIMARY KEY (id)
);

ALTER TABLE accounts
    ADD CONSTRAINT uc_accounts_accountnumber UNIQUE (account_number);

ALTER TABLE accounts
    ADD CONSTRAINT FK_ACCOUNTS_ON_CUSTOMER FOREIGN KEY (customer_id) REFERENCES customers (id);


CREATE TABLE bank_transactions
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE,
    transaction_id    VARCHAR(64)                             NOT NULL,
    type              VARCHAR(255)                            NOT NULL,
    amount            DECIMAL(19, 4)                          NOT NULL,
    balance_after     DECIMAL(19, 4)                          NOT NULL,
    account_id        BIGINT                                  NOT NULL,
    target_account_id BIGINT,
    description       VARCHAR(255),
    timestamp         TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    CONSTRAINT pk_bank_transactions PRIMARY KEY (id)
);

ALTER TABLE bank_transactions
    ADD CONSTRAINT uc_bank_transactions_transactionid UNIQUE (transaction_id);

ALTER TABLE bank_transactions
    ADD CONSTRAINT FK_BANK_TRANSACTIONS_ON_ACCOUNT FOREIGN KEY (account_id) REFERENCES accounts (id);

ALTER TABLE bank_transactions
    ADD CONSTRAINT FK_BANK_TRANSACTIONS_ON_TARGET_ACCOUNT FOREIGN KEY (target_account_id) REFERENCES accounts (id);


CREATE TABLE audit_logs
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE,
    username          VARCHAR(100)                            NOT NULL,
    action            VARCHAR(50)                             NOT NULL,
    resource          VARCHAR(50),
    resource_id       VARCHAR(100),
    description       VARCHAR(500),
    ip_address        VARCHAR(50),
    status            VARCHAR(20)                             NOT NULL,
    error_message     VARCHAR(500),
    execution_time_ms BIGINT,
    CONSTRAINT pk_audit_logs PRIMARY KEY (id)
);